def _exigir_integracao(x_integracao_token: str | None):
    secret = os.getenv("GFARM_RECEBIMENTOS_TOKEN", "")
    if not secret:
        raise HTTPException(503, "Integração não configurada no GFARM.")
    if not x_integracao_token or not hmac.compare_digest(x_integracao_token, secret):
        raise HTTPException(401, "Credencial da integração inválida.")


def _exigir_revisor(user: User):
    if not tem_permissao(user, "admin.estoque.entrada_manual"):
        raise HTTPException(403, "Somente um administrador autorizado pode revisar recebimentos.")


def _row(db: Session, origem_id: str):
    return db.execute(text("""
        SELECT id, origem_id, dados, status, motivo_recusa, documento_estoque_id,
               criado_em, atualizado_em, revisado_em
          FROM integracao_recebimentos_pendentes WHERE origem_id=:origem
    """), {"origem": origem_id}).mappings().first()


def _serial(row):
    return {
        "id": row["id"], "origem_id": row["origem_id"],
        "dados": row["dados"], "status": row["status"],
        "motivo_recusa": row["motivo_recusa"],
        "documento_estoque_id": row["documento_estoque_id"],
        "criado_em": row["criado_em"].isoformat() if row["criado_em"] else None,
        "revisado_em": row["revisado_em"].isoformat() if row["revisado_em"] else None,
    }


@router.post("")
def receber(dados: Recebimento, x_integracao_token: str | None = Header(None),
            db: Session = Depends(get_db)):
    _exigir_integracao(x_integracao_token)
    if dados.chave_acesso and (len(dados.chave_acesso) != 44 or not dados.chave_acesso.isdigit()):
        raise HTTPException(422, "Chave de acesso inválida.")
    payload = dados.model_dump(mode="json")
    atual = _row(db, dados.origem_id)
    if atual and atual["status"] != "PENDENTE":
        if atual["dados"] != payload:
            raise HTTPException(409, "O recebimento já foi revisado e não admite alteração.")
        return {"origem_id": dados.origem_id, "status": atual["status"]}
    updated = db.execute(text("""
        INSERT INTO integracao_recebimentos_pendentes (origem_id, dados)
        VALUES (:id, CAST(:dados AS JSONB))
        ON CONFLICT (origem_id) DO UPDATE
        SET dados = EXCLUDED.dados, atualizado_em = NOW()
        WHERE integracao_recebimentos_pendentes.status = 'PENDENTE'
        RETURNING origem_id
    """), {"id": dados.origem_id, "dados": json.dumps(payload, ensure_ascii=False)}).first()
    if updated is None:
        db.rollback()
        raise HTTPException(409, "Recebimento em revisão no GFARM; não é possível atualizar.")
    db.commit()
    return {"origem_id": dados.origem_id, "status": "PENDENTE"}


@router.delete("/{origem_id}")
def cancelar_origem(origem_id: str, x_integracao_token: str | None = Header(None),
                    db: Session = Depends(get_db)):
    """Cancelar somente pendência ainda não contabilizada, antes da exclusão no Controles."""
    _exigir_integracao(x_integracao_token)
    result = db.execute(text("""
        UPDATE integracao_recebimentos_pendentes
           SET status='CANCELADO', atualizado_em=NOW(), revisado_em=NOW()
         WHERE origem_id=:id AND status='PENDENTE' RETURNING id
    """), {"id": origem_id}).first()
    if result is None:
        db.rollback()
        raise HTTPException(409, "Recebimento não pode ser cancelado porque foi revisado ou está sendo processado.")
    db.commit()
    return {"status": "CANCELADO"}


@router.get("/status/{origem_id}")
def status_origem(origem_id: str, x_integracao_token: str | None = Header(None),
                  db: Session = Depends(get_db)):
    _exigir_integracao(x_integracao_token)
    row = _row(db, origem_id)
    if row is None:
        raise HTTPException(404, "Recebimento não encontrado.")
    return {"origem_id": origem_id, "status": row["status"],
            "documento_estoque_id": row["documento_estoque_id"],
            "motivo_recusa": row["motivo_recusa"]}


@router.get("")
def listar(status: Literal["PENDENTE", "PROCESSANDO", "APROVADO", "REJEITADO"] | None = None,
           user: User = Depends(get_current_user), db: Session = Depends(get_db)):
    _exigir_revisor(user)
    # O PostgreSQL, com psycopg, pode receber o mesmo bind Python como dois
    # parâmetros distintos. (:status IS NULL OR status = :status) deixa o
    # primeiro sem tipo inferível e causa "could not determine data type of
    # parameter $1". Aplicar o filtro somente quando há status evita isso.
    filtro = "WHERE status = :status" if status is not None else ""
    parametros = {"status": status} if status is not None else {}
    rows = db.execute(text(f"""
        SELECT id, origem_id, dados, status, motivo_recusa, documento_estoque_id,
               criado_em, atualizado_em, revisado_em
        FROM integracao_recebimentos_pendentes
        {filtro}
        ORDER BY criado_em DESC LIMIT 300
    """), parametros).mappings().all()
    return [_serial(row) for row in rows]


@router.post("/{origem_id}/recusar")
def recusar(origem_id: str, dados: Recusar, user: User = Depends(get_current_user),
            db: Session = Depends(get_db)):
    _exigir_revisor(user)
    result = db.execute(text("""
        UPDATE integracao_recebimentos_pendentes
           SET status='REJEITADO', motivo_recusa=:motivo, revisado_em=NOW(),
               atualizado_em=NOW()
         WHERE origem_id=:id AND status='PENDENTE' RETURNING id
    """), {"id": origem_id, "motivo": dados.motivo.strip()}).first()
    if not result:
        db.rollback()
        raise HTTPException(409, "Recebimento não está pendente.")
    db.commit()
    return {"status": "REJEITADO"}


@router.post("/{origem_id}/recuperar-custo-xml")
def recuperar_custo_xml(origem_id: str, dados: RecuperarCustoXml,
                       user: User = Depends(get_current_user),
                       db: Session = Depends(get_db)):
    """Importa os dados fiscais de uma NF-e para TODAS as pendências compatíveis.

    Confere chave, número, código ou descrição e unidades para cada produto.
    Registra custo, emitente, códigos, CFOP, NCM e rastreio quando inequívocos.
    Mantém nome/quantidade do recebimento (podem ser parciais), status e saldo.
    Nunca movimenta estoque nem aprova lançamentos.
    """
    _exigir_revisor(user)
    row = _row(db, origem_id)
    if row is None:
        raise HTTPException(404, "Recebimento não encontrado.")
    if row["status"] != "PENDENTE":
        raise HTTPException(409, "Somente recebimentos pendentes podem receber valores fiscais.")
    # A linha que abriu o FSist pode nao estar no XML. Neste caso,
    # aproveitamos os outros produtos da mesma chave sem exigir
    # correspondencia do item clicado como condicao para o lote inteiro.
    # Cada candidato e conferido individualmente: chave, numero e produto.
    # Uma única NF-e pode ter vários produtos; aproveitar o mesmo XML para
    # recuperar seus preços sem pedir que o usuário anexe o arquivo repetidamente.
    # Só atualizar itens cujo código/nome corresponda de forma inequívoca.
    chave = str(row["dados"].get("chave_acesso") or "")
    candidatos = db.execute(text("""
        SELECT origem_id, dados
          FROM integracao_recebimentos_pendentes
         WHERE status='PENDENTE' AND dados->>'chave_acesso'=:chave
         FOR UPDATE
    """), {"chave": chave}).mappings().all()
    atualizados = 0
    origens_atualizadas = []
    nao_identificados = []
    fiscal = None
    primeiro_erro = None
    for candidato in candidatos:
        try:
            campos = extrair_custo_xml(dados.xml, candidato["dados"])
        except DadosFiscaisIncompativeis as err:
            if primeiro_erro is None:
                primeiro_erro = str(err)
            nao_identificados.append(str(candidato["dados"].get("produto") or "Produto desconhecido"))
            continue
        if fiscal is None or candidato["origem_id"] == origem_id:
            fiscal = campos
        payload = {**candidato["dados"], **campos}
        db.execute(text("""
            UPDATE integracao_recebimentos_pendentes
               SET dados=CAST(:dados AS JSONB), atualizado_em=NOW()
             WHERE origem_id=:origem AND status='PENDENTE'
        """), {
            "origem": candidato["origem_id"],
            "dados": json.dumps(payload, ensure_ascii=False),
        })
        atualizados += 1
        origens_atualizadas.append(candidato["origem_id"])
    if not atualizados:
        db.rollback()
        raise HTTPException(
            422,
            primeiro_erro or "Nenhuma entrada pendente desta nota corresponde aos produtos do XML.",
        )
    db.commit()
    return {
        "origem_id": origem_id,
        "status": "PENDENTE",
        "valor_unitario": fiscal["valor_unitario"],
        "valor_total": fiscal["valor_total"],
        "custo_origem": fiscal["custo_origem"],
        "itens_atualizados": atualizados,
        "origens_atualizadas": origens_atualizadas,
        "nao_identificados": nao_identificados[:30],
    }


@router.post("/{origem_id}/aprovar")
def aprovar(origem_id: str, dados: Aprovar, user: User = Depends(get_current_user),
            db: Session = Depends(get_db)):
    _exigir_revisor(user)
    # O COMMIT do claim abaixo expira os objetos ORM (expire_on_commit=True).
    # Consultar user.id DEPOIS do commit dispara um SELECT implícito, abrindo
    # outra transação antes de movimentar_estoque() chamar db.begin().
    # Capturar o identificador antes do commit evita InvalidRequestError/HTTP 500.
    usuario_id = str(user.id)
    row = _row(db, origem_id)
    if row is None:
        raise HTTPException(404, "Recebimento não encontrado.")
    if row["status"] == "APROVADO":
        return {"status": "APROVADO", "documento_estoque_id": row["documento_estoque_id"]}
    if row["status"] not in ("PENDENTE", "PROCESSANDO"):
        raise HTTPException(409, "Recebimento já recusado.")
    if row["status"] == "PROCESSANDO":
        # A recuperação de uma tentativa interrompida é idempotente no motor.
        from datetime import datetime, timezone, timedelta
        if row["atualizado_em"] and row["atualizado_em"] > datetime.now(timezone.utc) - timedelta(minutes=5):
            raise HTTPException(409, "Outra aprovação está em processamento.")

    payload = row["dados"]
    produto = db.get(Produto, dados.produto_id)
    if produto is None:
        raise HTTPException(404, "Produto do GFARM não encontrado.")

    quantidade = dados.quantidade or Decimal(str(payload["quantidade"]))
    unidade = dados.unidade or payload["unidade"]
    try:
        if dados.fator_conversao is not None:
            fator = dados.fator_conversao
        else:
            fator = Decimal(str(converter_quantidade_estoque(produto, quantidade, unidade)["fator_conversao"]))
    except ValueError as err:
        raise HTTPException(422, str(err)) from err
    if fator <= 0:
        raise HTTPException(422, "Fator de conversão inválido.")
    if dados.custo_unitario_base is not None:
        # Ajuste excepcional e explícito do administrador.
        custo = dados.custo_unitario_base
    else:
        try:
            # Primeiro usa o total da NF-e; se não existir, usa vUnCom.
            # A conversão é feita sobre a quantidade ORIGINAL da nota,
            # sem distorção caso o administrador ajuste a entrada.
            custo = custo_unitario_na_base(payload, fator)
        except DadosFiscaisIncompativeis as err:
            raise HTTPException(422, str(err)) from err
    validade = dados.validade.isoformat() if dados.validade else (payload.get("validade") or None)
    # Transição antes da chamada ao motor; impede aprovação/recusa concorrente.
    claimed = db.execute(text("""
        UPDATE integracao_recebimentos_pendentes
           SET status='PROCESSANDO', atualizado_em=NOW()
         WHERE origem_id=:id
           AND (status='PENDENTE' OR (status='PROCESSANDO'
                AND atualizado_em < NOW() - INTERVAL '5 minutes'))
        RETURNING id
    """), {"id": origem_id}).first()
    if claimed is None:
        db.rollback()
        raise HTTPException(409, "Recebimento já está sendo revisado.")
    db.commit()

    item = {
        "produto_id": dados.produto_id, "quantidade": str(quantidade),
        "unidade": unidade, "deposito_destino_id": dados.deposito_id,
        "gaveta_destino_id": dados.gaveta_id or "",
        "custo_unitario": str(custo),
    }
    if dados.fator_conversao is not None:
        item["fator_conversao"] = str(dados.fator_conversao)
    if validade:
        item["data_validade"] = validade
    observacao = (
        f"Meus Controles | NF {payload['numero_nota']} série {payload.get('serie','')} "
        f"| chave {payload.get('chave_acesso','')} | fornecedor {payload.get('fornecedor','')} "
        f"| pedido {payload.get('numero_pedido','')} | CFOP {payload.get('cfop','')} "
        f"| NCM {payload.get('ncm','')} | lote informado {payload.get('lote','')}"
    )
    try:
        db.rollback()  # motor abre sua própria transação
        documento = movimentar_estoque(
            db, tipo_movimento="ENTRADA_COMPRA", usuario_id=usuario_id,
            itens=[item], origem_modulo="controles_recebimentos",
            documento_origem_id=origem_id,
            referencia_externa=payload.get("chave_acesso") or payload["numero_nota"],
            observacao=observacao,
        )
        numero = str(documento.id)
        db.rollback()
        db.execute(text("""
            UPDATE integracao_recebimentos_pendentes
               SET status='APROVADO', documento_estoque_id=:doc,
                   revisado_em=NOW(), atualizado_em=NOW()
             WHERE origem_id=:id AND status='PROCESSANDO'
        """), {"id": origem_id, "doc": numero})
        db.commit()
        return {"status": "APROVADO", "documento_estoque_id": numero}
    except Exception as err:
        db.rollback()
        db.execute(text("""
            UPDATE integracao_recebimentos_pendentes
               SET status='PENDENTE', atualizado_em=NOW()
             WHERE origem_id=:id AND status='PROCESSANDO'
        """), {"id": origem_id})
        db.commit()
        if isinstance(err, (EstoqueErro, ValueError)):
            raise HTTPException(422, str(err)) from err
        raise
