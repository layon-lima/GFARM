def garantir_tabela_recebimentos():
    with engine.begin() as db:
        db.execute(text("""
            CREATE TABLE IF NOT EXISTS integracao_recebimentos_pendentes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                origem_id VARCHAR(100) NOT NULL UNIQUE,
                dados JSONB NOT NULL,
                status VARCHAR(24) NOT NULL DEFAULT 'PENDENTE',
                motivo_recusa TEXT,
                documento_estoque_id VARCHAR(100),
                criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                revisado_em TIMESTAMPTZ
            )
        """))
        db.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_integracao_recebimentos_status
            ON integracao_recebimentos_pendentes (status, criado_em DESC)
        """))


class Recebimento(BaseModel):
    origem_id: str = Field(min_length=1, max_length=100)
    numero_nota: str = Field(min_length=1, max_length=100)
    chave_acesso: str = Field(default="", max_length=44)
    serie: str = Field(default="", max_length=20)
    data_emissao: str = Field(default="", max_length=32)
    data_recebimento: str = Field(default="", max_length=32)
    fornecedor: str = Field(default="", max_length=240)
    documento_fornecedor: str = Field(default="", max_length=20)
    numero_pedido: str = Field(default="", max_length=100)
    produto: str = Field(min_length=1, max_length=255)
    codigo_produto: str = Field(default="", max_length=100)
    quantidade: Decimal = Field(gt=0)
    unidade: str = Field(min_length=1, max_length=30)
    valor_unitario: Decimal | None = Field(default=None, ge=0)
    valor_total: Decimal | None = Field(default=None, ge=0)
    cfop: str = Field(default="", max_length=10)
    ncm: str = Field(default="", max_length=12)
    lote: str = Field(default="", max_length=100)
    validade: str = Field(default="", max_length=10)
    origem_arquivo: str = Field(default="manual", max_length=30)


class Aprovar(BaseModel):
    produto_id: str = Field(min_length=1, max_length=100)
    deposito_id: str = Field(min_length=1, max_length=100)
    gaveta_id: str | None = None
